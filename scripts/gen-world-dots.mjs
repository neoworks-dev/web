// Regenerates src/lib/worldDots.ts — the dotted world map used by
// ActiveUsersMap.svelte. Downloads Natural Earth country polygons and rasterizes
// them into a grid of dots, each tagged with the country it falls in.
//
// Usage:  node scripts/gen-world-dots.mjs
// Tune the dot density with STEP (smaller = more dots).

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const SOURCE =
	'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson';
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'worldDots.ts');

// Equirectangular projection + output viewBox.
const LON_MIN = -180, LON_MAX = 180, LAT_MAX = 82, LAT_MIN = -56, VIEW_W = 200;
const VIEW_H = (VIEW_W * (LAT_MAX - LAT_MIN)) / (LON_MAX - LON_MIN);
const STEP = 2.2; // degrees between dots
const px = (lon) => ((lon - LON_MIN) / (LON_MAX - LON_MIN)) * VIEW_W;
const py = (lat) => ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * VIEW_H;

function code(p) {
	let c = p.ISO_A2_EH;
	if (!c || c === '-99') c = p.ISO_A2;
	if (!c || c === '-99') c = p.ADM0_A3 || '';
	return c;
}

function inRings(lon, lat, rings) {
	let inside = false;
	for (const ring of rings) {
		for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
			const xi = ring[i][0], yi = ring[i][1], xj = ring[j][0], yj = ring[j][1];
			if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
		}
	}
	return inside;
}

const geo = await (await fetch(SOURCE)).json();

const countries = [];
for (const f of geo.features) {
	const geom = f.geometry;
	if (!geom) continue;
	const polyList = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;
	const polys = [];
	for (const poly of polyList) {
		let minx = Infinity, miny = Infinity, maxx = -Infinity, maxy = -Infinity;
		for (const ring of poly) for (const [x, y] of ring) {
			if (x < minx) minx = x; if (x > maxx) maxx = x;
			if (y < miny) miny = y; if (y > maxy) maxy = y;
		}
		polys.push({ bbox: [minx, miny, maxx, maxy], rings: poly });
	}
	countries.push({ c: code(f.properties), polys });
}

const codes = [];
const codeIdx = new Map();
const ci = (c) => {
	if (!codeIdx.has(c)) { codeIdx.set(c, codes.length); codes.push(c); }
	return codeIdx.get(c);
};

const dots = [];
for (let lat = LAT_MAX; lat >= LAT_MIN; lat -= STEP) {
	for (let lon = LON_MIN; lon <= LON_MAX; lon += STEP) {
		let found = null;
		for (const country of countries) {
			for (const poly of country.polys) {
				const b = poly.bbox;
				if (lon < b[0] || lon > b[2] || lat < b[1] || lat > b[3]) continue;
				if (inRings(lon, lat, poly.rings)) { found = country.c; break; }
			}
			if (found !== null) break;
		}
		if (found !== null) dots.push([+px(lon).toFixed(1), +py(lat).toFixed(1), ci(found)]);
	}
}

const out =
	`// AUTO-GENERATED by scripts/gen-world-dots.mjs from Natural Earth\n` +
	`// ne_110m_admin_0_countries. Do not edit by hand — re-run the script.\n` +
	`// Each dot is [x, y, countryIndex] in a ${VIEW_W}x${VIEW_H.toFixed(2)} viewBox.\n` +
	`export const VIEW_W = ${VIEW_W};\n` +
	`export const VIEW_H = ${+VIEW_H.toFixed(2)};\n` +
	`export const DOT_CODES: string[] = ${JSON.stringify(codes)};\n` +
	`export const DOTS: [number, number, number][] = ${JSON.stringify(dots)};\n`;

fs.writeFileSync(OUT, out);
console.log(`wrote ${OUT}: ${dots.length} dots, ${codes.length} countries`);
